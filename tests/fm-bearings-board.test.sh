test_build_refuses_malformed_payloads_before_touching_the_board() {
  local home data board rc out
  home=$(make_home refusal)
  board="$home/.lavish/bearings-board.html"
  data="$home/payload.json"

  printf 'not json\n' > "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a non-JSON payload was accepted"
  assert_contains "$out" "not valid JSON" "the non-JSON refusal did not say why: $out"

  printf '{"schema":"fm-bearings-board.v1"}\n' > "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a superseded-schema payload was accepted"
  assert_contains "$out" "fm-bearings-board.v2" "the schema refusal did not name the contract: $out"

  write_valid_payload "$data"
  jq '.captains_call[0].key = (reduce range(129) as $i (""; . + "x"))' "$data" > "$data.tmp" \
    && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a 129-char captains_call key was accepted"

  write_valid_payload "$data"
  jq 'del(.charted[0].dispatchable)' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a charted row without a dispatchable boolean was accepted"

  write_valid_payload "$data"
  jq '.charted[0].kind = "alarm"' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "an unknown charted kind was accepted"

  write_valid_payload "$data"
  jq '.charted[0].kind = "warning"' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a dispatchable warning row was accepted"

  write_valid_payload "$data"
  jq '.charted_warning_more = -1' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a negative omitted-warning count was accepted"

  write_valid_payload "$data"
  jq '.captains_call[0].type = "verdict"' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "an unknown captains_call type was accepted"

  write_valid_payload "$data"
  jq 'del(.captains_call[0].options[0].value)' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a captains_call option without an answer value was accepted"

  write_valid_payload "$data"
  jq '.captains_call[0].options[0].label = ""' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a captains_call option with an empty label was accepted"

  write_valid_payload "$data"
  jq 'del(.charted[0].repo)' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a fleet row without an explicit repo marker was accepted"

  write_valid_payload "$data"
  jq '.captains_call[0].allow_freeform = "yes"' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a non-boolean renderer field was accepted"

  write_valid_payload "$data"
  jq '.captains_call[0].options = [] | .captains_call[0].allow_freeform = false' "$data" > "$data.tmp" \
    && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "an unanswerable captains_call item was accepted"

  write_valid_payload "$data"
  jq '.captains_call[1].pr_url = "javascript:alert(1)"' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a non-HTTPS Captain’s Call PR URL was accepted"

  write_valid_payload "$data"
  jq '.landed = [{
    "id": "sample-landed",
    "repo": "sample",
    "what": "Landed work",
    "owner": "firstmate",
    "landed_on": "2026-08-18",
    "pr_url": "data:text/html,unsafe"
  }]' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a non-HTTPS Landed PR URL was accepted"

  assert_absent "$board" "a refused payload still produced a board"
  pass "build refuses malformed payloads before touching the board"
}

# The v2 invariants exist so the yard read cannot silently degrade back into a
# flat checklist: the board measures every age against `generated`, states a
# recorded date or an explicit "none", and can always say what holds a berth.
test_v2_refuses_rows_the_yard_could_not_read() {
  local home data board rc out
  home=$(make_home yardschema)
  board="$home/.lavish/bearings-board.html"
  data="$home/payload.json"

  write_valid_payload "$data"
  jq '.generated = "just now"' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a generated stamp with no date was accepted"

  write_valid_payload "$data"
  jq 'del(.charted[0].since)' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a charted row that omits its since marker was accepted"

  write_valid_payload "$data"
  jq '.landed = [{"id":"l","repo":"sample","what":"Landed","owner":"firstmate"}]' "$data" \
    > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a landed row that omits its landed_on marker was accepted"

  # a dry-dock berth that cannot say what holds it is indistinguishable from an
  # order that is merely waiting for a crew, which is the defect being fixed
  write_valid_payload "$data"
  jq '.charted[0].dispatchable = false' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "a held charted row with no reason was accepted"

  assert_absent "$board" "a refused payload still produced a board"

  # an explicit null is the deliberate "this row records no date" marker, and
  # a held row that names its blocker is exactly what dry dock renders
  write_valid_payload "$data"
  jq '.charted[0].since = null
      | .charted += [{"id":"held","repo":"sample","title":"Held work",
                      "reason":"blocked on the cutover","dispatchable":false,"since":"2026-08-01"}]
      | .landed = [{"id":"l","repo":"sample","what":"Landed","owner":"firstmate","landed_on":null}]' \
    "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  run_board "$home" build "$data" >/dev/null \
    || fail "explicit null dates and a reasoned held row were refused"
  pass "v2 refuses undated and unexplained rows while accepting explicit null dates"
}

# `since` and `landed_on` come from hand-edited backlog markdown, where the
# metadata reader takes whatever follows the keyword. "(since the pivot)" is an
# ordinary note, and one of them must never cost the captain the whole board.
# The key must still be present - only the shape of its VALUE is tolerated.
test_v2_tolerates_a_recorded_date_that_is_not_a_date() {
  local home data board rc
  home=$(make_home yardprose)
  board="$home/.lavish/bearings-board.html"
  data="$home/payload.json"

  write_valid_payload "$data"
  jq '.charted[0].since = "the pivot"
      | .landed = [{"id":"l","repo":"sample","what":"Landed","owner":"firstmate",
                    "landed_on":"last sprint"}]' \
    "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  run_board "$home" build "$data" >/dev/null \
    || fail "a backlog note where a date was expected refused the whole board"
  assert_present "$board" "the board is missing after a tolerated non-date value"

  # `generated` is the snapshot's own stamp, not hand-written, and every age is
  # measured against it, so it stays strictly a date.
  write_valid_payload "$data"
  jq '.generated = "just now"' "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  set +e; run_board "$home" build "$data" >/dev/null 2>&1; rc=$?; set -e
  [ "$rc" -ne 0 ] || fail "the reference stamp was allowed to stop being a date"
  pass "a recorded value that is not a date is tolerated, but generated is not"
}

# `charted_more` is a FLEET count and names no project, so a lane whose rows all
# fell past a bound had nothing to disclose and read as launched-and-quiet, or
# never appeared at all. `lanes_more` is that same disclosure per lane, and the
# template both seeds a lane from an entry and prints its counts, so an entry
# the board cannot stand behind is refused before the built board is touched.
test_v2_refuses_lane_omissions_the_board_could_not_stand_behind() {
  local home data board rc out
  home=$(make_home lanesmore)
  board="$home/.lavish/bearings-board.html"
  data="$home/payload.json"

  refuse() {  # <jq-program> <what>
    write_valid_payload "$data"
    jq "$1" "$data" > "$data.tmp" && mv "$data.tmp" "$data"
    set +e; out=$(run_board "$home" build "$data" 2>&1); rc=$?; set -e
    [ "$rc" -ne 0 ] || fail "$2 was accepted"
  }

  # an entry that omits nothing would seed a lane with nothing to say
  refuse '.lanes_more = [{"repo":"sample","queued":0,"underway":0,"call":0}]' \
    "a lane omission of nothing"
  # two entries for one lane are two answers to the same question, and the lane
  # key is the trimmed repo, so a padded repeat is the same lane
  refuse '.charted_more = 4
          | .lanes_more = [{"repo":"sample","queued":2,"underway":0,"call":0},
                           {"repo":" sample ","queued":2,"underway":0,"call":0}]' \
    "two omission entries for one lane"
  # the same deliberate-marker discipline every row uses
  refuse '.charted_more = 2 | .lanes_more = [{"queued":2,"underway":0,"call":0}]' \
    "a lane omission with no repo marker"
  refuse '.charted_more = 2 | .lanes_more = [{"repo":"sample","underway":0,"call":0}]' \
    "a lane omission missing one of its counts"
  refuse '.charted_more = 2 | .lanes_more = [{"repo":"sample","queued":1.5,"underway":0,"call":0}]' \
    "a fractional lane omission count"
  refuse '.charted_more = 2 | .lanes_more = [{"repo":"sample","queued":-1,"underway":1,"call":0}]' \
    "a negative lane omission count"
  refuse '.lanes_more = {"sample":2}' "a lane omission that is not an array"
  # the lanes may not between them claim more withheld queued work than the yard
  # admits: the rail counts the order book as what it holds plus charted_more
  refuse '.charted_more = 2 | .lanes_more = [{"repo":"sample","queued":3,"underway":0,"call":0}]' \
    "lane omissions adding up past the yard total"
  # and withholding queued work without declaring the total at all would print
  # lane depth the yard itself denies
  refuse 'del(.charted_more) | .lanes_more = [{"repo":"sample","queued":3,"underway":0,"call":0}]' \
    "withheld queued work the yard never declared"

  assert_absent "$board" "a refused payload still produced a board"

  # accepted: the marker null lane, a withheld feed with no fleet counterpart to
  # reconcile against, and lane counts that fit inside the yard total
  write_valid_payload "$data"
  jq '.charted_more = 5
      | .lanes_more = [{"repo":"sample","queued":3,"underway":1,"call":0},
                       {"repo":null,"queued":0,"underway":0,"call":2}]' \
    "$data" > "$data.tmp" && mv "$data.tmp" "$data"
  run_board "$home" build "$data" >/dev/null \
    || fail "a lane omission the board can stand behind was refused"
  # a payload that says nothing about lane omissions is still a valid payload:
  # the field is what a composer uses to disclose, never a new requirement
  write_valid_payload "$data"
  run_board "$home" build "$data" >/dev/null \
    || fail "a payload with no lane omissions at all was refused"
  pass "v2 refuses lane omissions the board could not stand behind"
}

test_build_injects_binds_then_arms() {
  local home data board out sid
  home=$(make_home build)
  data="$home/payload.json"
  board="$home/.lavish/bearings-board.html"
  write_valid_payload "$data"

  out=$(run_board "$home" build "$data") || fail "a valid payload did not build"
  assert_contains "$out" "board: $board" "build did not report the board path: $out"
  assert_contains "$out" "served: $board" "build did not establish the Lavish session: $out"
  assert_contains "$out" "bound: " "build did not report the answer binding: $out"
  assert_contains "$out" "armed: " "the first build did not arm the board source: $out"
  assert_present "$board" "build reported success without a board"

  # Round-trip: the payload extracted from the built page is byte-for-byte the
  # same JSON document, and the escaped </script> string can no longer
  # terminate the data block.
  extract_payload "$board" | jq -S . > "$home/extracted.json" \
    || fail "the built board does not carry parseable payload JSON"
  jq -S . "$data" > "$home/expected.json"
  diff -u "$home/expected.json" "$home/extracted.json" >/dev/null \
    || fail "the injected payload does not round-trip to the input document"
  grep -qF '</script><b>' "$board" \
    && fail "a payload string embedded a live closing script tag in the page"
  grep -qxF '__FM_BEARINGS_BOARD_DATA__' "$board" \
    && fail "the data slot survived injection"

  sid=$(run_lavish_source_id "$home" "$board")
  assert_contains "$out" "bound: $sid" "the binding does not name the board source: $out"
  [ "$(run_decisions "$home" binding "$sid")" = "(any)" ] \
    || fail "the board source is not bound any-origin"
  run_procevent "$home" list | awk 'NR > 1 { print $1 }' | grep -Fxq "$sid" \
    || fail "the board source is not registered after build"
  pass "build injects the payload, binds any-origin, then arms the source"
}

